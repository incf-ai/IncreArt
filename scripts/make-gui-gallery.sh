#!/usr/bin/env bash
# Writes docs/gui/GALLERY.md: every screenshot in docs/gui, in file-name
# order, full width with its caption from the table in docs/gui/README.md.
# Run after the screenshot tour or after editing the README's captions:
#
#   scripts/make-gui-gallery.sh
set -euo pipefail
cd "$(dirname "$0")/../docs/gui"
export LC_ALL=C

# | [03-idea-inbox-grid](03-idea-inbox-grid.webp) | caption |
ls -- *.webp | awk '
    FNR == NR {
        if (match($0, /^\|[ \t]*\[[^]]+\]\([^)]+\.webp\)[ \t]*\|/) && $0 ~ /\|[ \t]*$/) {
            link = substr($0, 1, RLENGTH)
            cap = substr($0, RLENGTH + 1)
            sub(/^.*\]\(/, "", link); sub(/\).*$/, "", link)
            sub(/^[ \t]+/, "", cap); sub(/[ \t]*\|[ \t]*$/, "", cap)
            caps[link] = cap
        }
        next
    }
    { shots[++n] = $0 }
    END {
        print "# IncreArt GUI gallery\n"
        print "Every screenshot in order, full size. Generated by"
        print "`scripts/make-gui-gallery.sh` from the captions in the"
        print "[screens table](README.md); don'"'"'t edit by hand.\n"
        for (i = 1; i <= n; i++) {
            stem = shots[i]; sub(/\.webp$/, "", stem)
            print "## " stem "\n"
            if (shots[i] in caps) print caps[shots[i]] "\n"; else missing[++m] = shots[i]
            print "![" stem "](" shots[i] ")" (i < n ? "\n" : "")
        }
        printf "%d screenshots, %d without a caption\n", n, m > "/dev/stderr"
        for (i = 1; i <= m; i++) print "  no caption: " missing[i] > "/dev/stderr"
    }
' README.md - > GALLERY.md
